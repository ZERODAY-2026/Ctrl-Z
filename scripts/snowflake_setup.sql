-- DataMind: reproducible Snowflake setup for a (free trial) account.
-- Run in a Snowsight worksheet as ACCOUNTADMIN (or a role allowed to create roles, warehouses, databases, users).
-- Creates: an X-Small auto-suspending warehouse, a read-only role, a service user (key-pair auth),
-- and a writable copy of TPC-H SF1 used ONLY to demonstrate "answers change when data changes".

USE ROLE ACCOUNTADMIN;

-- 1. Small warehouse that suspends after 60 s idle and cancels long statements.
CREATE WAREHOUSE IF NOT EXISTS DATAMIND_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 120;

-- 2. Least-privilege, read-only role.
CREATE ROLE IF NOT EXISTS DATAMIND_READER;
GRANT USAGE ON WAREHOUSE DATAMIND_WH TO ROLE DATAMIND_READER;
-- If SNOWFLAKE_SAMPLE_DATA is missing in your account, create it first:
--   CREATE DATABASE SNOWFLAKE_SAMPLE_DATA FROM SHARE SFC_SAMPLES.SAMPLE_DATA;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DATAMIND_READER;

-- 3. Writable demo copy (data stays inside your account; nothing is copied into the repository).
CREATE DATABASE IF NOT EXISTS DATAMIND_DEMO;
CREATE SCHEMA IF NOT EXISTS DATAMIND_DEMO.TPCH;
USE WAREHOUSE DATAMIND_WH;
CREATE OR REPLACE TABLE DATAMIND_DEMO.TPCH.REGION   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION;
CREATE OR REPLACE TABLE DATAMIND_DEMO.TPCH.NATION   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION;
CREATE OR REPLACE TABLE DATAMIND_DEMO.TPCH.CUSTOMER AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER;
CREATE OR REPLACE TABLE DATAMIND_DEMO.TPCH.ORDERS   AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;
CREATE OR REPLACE TABLE DATAMIND_DEMO.TPCH.LINEITEM AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM;
CREATE OR REPLACE TABLE DATAMIND_DEMO.TPCH.PART     AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART;
CREATE OR REPLACE TABLE DATAMIND_DEMO.TPCH.SUPPLIER AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER;
CREATE OR REPLACE TABLE DATAMIND_DEMO.TPCH.PARTSUPP AS SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PARTSUPP;
GRANT USAGE ON DATABASE DATAMIND_DEMO TO ROLE DATAMIND_READER;
GRANT USAGE ON SCHEMA DATAMIND_DEMO.TPCH TO ROLE DATAMIND_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA DATAMIND_DEMO.TPCH TO ROLE DATAMIND_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATAMIND_DEMO.TPCH TO ROLE DATAMIND_READER;

-- 4. Service user for the app. Generate a key pair with `python scripts/generate_keypair.py`
--    and paste the PUBLIC key body (no header/footer lines) below.
CREATE USER IF NOT EXISTS DATAMIND_APP
  TYPE = SERVICE
  DEFAULT_ROLE = DATAMIND_READER
  DEFAULT_WAREHOUSE = DATAMIND_WH
  RSA_PUBLIC_KEY = '<paste public key here>';
GRANT ROLE DATAMIND_READER TO USER DATAMIND_APP;

